#!/usr/bin/env python3
"""Generate HLE import stub symbols from the measured import matrix.

ReXGlue-generated PPC code calls Windows-style import symbols directly,
e.g. __imp__DbgPrint, __imp__NtCreateFile. On Android/ELF we can satisfy those
symbols with plain C functions. Each stub forwards to the runtime's name-based
dispatch so missing handlers are counted and reported instead of crashing.

Input:  config/hle_imports.json  (216 names measured from generated .obj files)
Output: native/src/import_stubs.cpp

Regenerate whenever the codegen import set changes. Never hand-edit output.
"""

from __future__ import annotations

import json
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
INPUT = PROJECT / "config/hle_imports.json"
OUTPUT = PROJECT / "native/src/import_stubs.cpp"


def main() -> int:
    names = json.loads(INPUT.read_text(encoding="utf-8"))
    if not names:
        raise SystemExit("empty import list")

    lines = [
        "// GENERATED by tools/gen_import_stubs.py from config/hle_imports.json.",
        "// DO NOT EDIT. Stubs forward to the runtime's name-based HLE dispatch.",
        "",
        '#include "hle_kernel.h"',
        "",
        "#include <cstdint>",
        "",
        "namespace {",
        "uint64_t stub(const char* name, PPCContext& ctx, uint8_t* base) {",
        "  return hle::Kernel::instance().call_named(name, ctx, base);",
        "}",
        "}  // namespace",
        "",
    ]
    for name in names:
        # rex:: runtime symbols have real implementations in runtime_symbols.cpp
        # with their native signatures; a generic (ctx, base) stub is wrong.
        if name.startswith("ZN3rex"):
            continue
        lines.append('extern "C" uint64_t __imp__' + name +
                     "(PPCContext& ctx, uint8_t* base) {")
        lines.append(f'  return stub("{name}", ctx, base);')
        lines.append("}")
        lines.append("")

    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"generated {len(names)} import stubs -> {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
