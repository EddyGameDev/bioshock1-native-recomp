#!/usr/bin/env python3
"""Generate no-op runtime symbols required to link the generated PPC code.

config/runtime_symbols.json is produced by tools/extract_runtime_symbols.py.
Each symbol becomes a distinct no-op function bound to the exact linker name
via a GCC/Clang asm label, so Android ELF resolution succeeds. These are
link-time placeholders only:

  * __rest* / __save* ABI helpers: must later be implemented properly (they
    save/restore non-volatile guest registers); no-ops let us link and boot.
  * rex:: runtime functions: need clean-room implementations.
  * xstart / compiler atomics: normally supplied by crt/compiler-rt; stubs are
    provided only when the standalone link test needs them.

Regenerate after re-running codegen. Never hand-edit the output.
"""

from __future__ import annotations

import json
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
INPUT = PROJECT / "config/runtime_non_abi.json"
OUTPUT = PROJECT / "native/src/runtime_stubs.cpp"


def safe_c_name(symbol: str) -> str:
    out = "bs_stub_" + "".join(c if c.isalnum() else "_" for c in symbol)
    return out[:180]


def main() -> int:
    symbols = json.loads(INPUT.read_text(encoding="utf-8"))
    lines = [
        "// GENERATED by tools/gen_runtime_stubs.py from config/runtime_symbols.json.",
        "// LINK-TIME PLACEHOLDERS. DO NOT EDIT; regenerate after codegen changes.",
        "",
        "#include <cstdint>",
        "",
        "namespace {",
        "uint64_t noop() { return 0; }",
        "}  // namespace",
        "",
    ]
    for symbol in symbols:
        alias = safe_c_name(symbol)
        lines.append(f'extern "C" uint64_t {alias}() __asm__("{symbol}");')
        lines.append(f"extern \"C\" uint64_t {alias}() {{ return noop(); }}")
        lines.append("")
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"generated {len(symbols)} runtime symbol stubs -> {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
