#!/usr/bin/env python3
"""Generate native/include/ppc_accessors.h.

ReXGlue names FPR/VMX fields individually (f0..f31, v0..v127); our standalone
context uses arrays. This generated header uses X-macros so runtime code can
access either layout through the same fpr_read/fpr_write/vmx_ptr functions.
"""

from __future__ import annotations

from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
OUT = PROJECT / "native/include/ppc_accessors.h"

fpr_list = " ".join(f"X({i})" for i in range(32))
vmx_list = " ".join(f"X({i})" for i in range(128))

content = f'''// GENERATED by tools/gen_ppc_accessors.py — DO NOT EDIT.
#pragma once

#include "ppc_context.h"

#include <cstdint>

#define BS_FPR_LIST(X) {fpr_list}
#define BS_VMX_LIST(X) {vmx_list}

inline uint64_t fpr_read(const PPCContext& ctx, int n) {{
#if defined(BS_USE_REX_CONTEXT)
    switch (n) {{
#define X(i) case i: return ctx.f##i.u64;
        BS_FPR_LIST(X)
#undef X
        default: return 0;
    }}
#else
    return (n >= 0 && n < 32) ? ctx.fpr[n] : 0;
#endif
}}

inline void fpr_write(PPCContext& ctx, int n, uint64_t value) {{
#if defined(BS_USE_REX_CONTEXT)
    switch (n) {{
#define X(i) case i: ctx.f##i.u64 = value; break;
        BS_FPR_LIST(X)
#undef X
        default: break;
    }}
#else
    if (n >= 0 && n < 32) ctx.fpr[n] = value;
#endif
}}

inline uint8_t* vmx_ptr(PPCContext& ctx, int n) {{
#if defined(BS_USE_REX_CONTEXT)
    switch (n) {{
#define X(i) case i: return ctx.v##i.u8;
        BS_VMX_LIST(X)
#undef X
        default: return nullptr;
    }}
#else
    return (n >= 0 && n < 128) ? ctx.vmx[n].data() : nullptr;
#endif
}}
'''

OUT.write_text(content, encoding="utf-8")
print(f"generated {OUT.relative_to(PROJECT)}")
