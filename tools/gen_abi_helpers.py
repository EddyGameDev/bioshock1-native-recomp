#!/usr/bin/env python3
"""Generate native/src/abi_helpers.cpp from measured XDK helper semantics.

The semantics were derived by disassembling the real XDK CRT helpers in the
decrypted game image (_work/default_unpacked) and from ReXGlue's authoritative
helper naming in src/codegen/phase_register.cpp:

  __{save,rest}gprlr_N  N=14..31   r1-based,   -0x98 + 8*(i-14), 64-bit
  __{save,rest}fpr_N    N=14..31   r12-based,  -0x90 + 8*(i-14), 64-bit
  __{save,rest}vmx_N    N=14..31   r12-based,  -0x120 + 16*(i-14), 128-bit
  __{save,rest}vmx_N    N=64..127  r12-based,  -0x400 + 16*(i-64), 128-bit

GPR helpers also save/restore LR through r12 at r1-8 (32-bit).
"""

from __future__ import annotations

import json
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
SYMBOLS = PROJECT / "config/runtime_symbols.json"
OUT = PROJECT / "native/src/abi_helpers.cpp"

PREAMBLE = '''// GENERATED by tools/gen_abi_helpers.py — DO NOT EDIT.
// Faithful native implementations of the Xbox 360 XDK register save/restore
// CRT helpers. Semantics measured from the decrypted game image.
#include "ppc_accessors.h"

#include <cstdint>
#include <cstring>

namespace {

void store_be64(uint8_t* base, uint32_t addr, uint64_t value) {
    const uint64_t be = __builtin_bswap64(value);
    std::memcpy(base + addr, &be, 8);
}
uint64_t load_be64(const uint8_t* base, uint32_t addr) {
    uint64_t be = 0;
    std::memcpy(&be, base + addr, 8);
    return __builtin_bswap64(be);
}
void store_be32(uint8_t* base, uint32_t addr, uint32_t value) {
    const uint32_t be = __builtin_bswap32(value);
    std::memcpy(base + addr, &be, 4);
}
uint32_t load_be32(const uint8_t* base, uint32_t addr) {
    uint32_t be = 0;
    std::memcpy(&be, base + addr, 4);
    return __builtin_bswap32(be);
}

// Xenos VMX registers are stored as four big-endian 32-bit words.
void store_vmx(uint8_t* base, uint32_t addr, const uint8_t* src) {
    uint8_t dst[16];
    for (int w = 0; w < 4; ++w) {
        uint32_t be = 0;
        std::memcpy(&be, src + w * 4, 4);
        be = __builtin_bswap32(be);
        std::memcpy(dst + w * 4, &be, 4);
    }
    std::memcpy(base + addr, dst, 16);
}
void load_vmx(const uint8_t* base, uint32_t addr, uint8_t* dst) {
    uint8_t src[16];
    std::memcpy(src, base + addr, 16);
    for (int w = 0; w < 4; ++w) {
        uint32_t be = 0;
        std::memcpy(&be, src + w * 4, 4);
        be = __builtin_bswap32(be);
        std::memcpy(dst + w * 4, &be, 4);
    }
}

void save_gpr(PPCContext& ctx, uint8_t* base, int start) {
    const uint32_t sp = static_cast<uint32_t>(gpr_read(ctx, 1));
    for (int i = start; i <= 31; ++i) {
        store_be64(base, sp + static_cast<uint32_t>(-0x98 + 8 * (i - 14)), gpr_read(ctx, i));
    }
    store_be32(base, sp - 8, static_cast<uint32_t>(link_register(ctx)));
}
void rest_gpr(PPCContext& ctx, uint8_t* base, int start) {
    const uint32_t sp = static_cast<uint32_t>(gpr_read(ctx, 1));
    for (int i = start; i <= 31; ++i) {
        gpr_write(ctx, i, load_be64(base, sp + static_cast<uint32_t>(-0x98 + 8 * (i - 14))));
    }
    set_link_register(ctx, load_be32(base, sp - 8));
}

void save_fpr(PPCContext& ctx, uint8_t* base, int start) {
    const uint32_t fp = static_cast<uint32_t>(gpr_read(ctx, 12));
    for (int i = start; i <= 31; ++i) {
        store_be64(base, fp + static_cast<uint32_t>(-0x90 + 8 * (i - 14)), fpr_read(ctx, i));
    }
}
void rest_fpr(PPCContext& ctx, uint8_t* base, int start) {
    const uint32_t fp = static_cast<uint32_t>(gpr_read(ctx, 12));
    for (int i = start; i <= 31; ++i) {
        fpr_write(ctx, i, load_be64(base, fp + static_cast<uint32_t>(-0x90 + 8 * (i - 14))));
    }
}

void save_vmx(PPCContext& ctx, uint8_t* base, int start) {
    const uint32_t fp = static_cast<uint32_t>(gpr_read(ctx, 12));
    if (start >= 64) {
        for (int i = start; i <= 127; ++i) {
            store_vmx(base, fp + static_cast<uint32_t>(-0x400 + 16 * (i - 64)), vmx_ptr(ctx, i));
        }
    } else {
        for (int i = start; i <= 31; ++i) {
            store_vmx(base, fp + static_cast<uint32_t>(-0x120 + 16 * (i - 14)), vmx_ptr(ctx, i));
        }
    }
}
void rest_vmx(PPCContext& ctx, uint8_t* base, int start) {
    const uint32_t fp = static_cast<uint32_t>(gpr_read(ctx, 12));
    if (start >= 64) {
        for (int i = start; i <= 127; ++i) {
            load_vmx(base, fp + static_cast<uint32_t>(-0x400 + 16 * (i - 64)), vmx_ptr(ctx, i));
        }
    } else {
        for (int i = start; i <= 31; ++i) {
            load_vmx(base, fp + static_cast<uint32_t>(-0x120 + 16 * (i - 14)), vmx_ptr(ctx, i));
        }
    }
}

}  // namespace
'''


def main() -> int:
    wanted = set(json.loads(SYMBOLS.read_text(encoding="utf-8")))
    lines = [PREAMBLE]
    implemented = set()
    groups = [
        ("savegprlr", save := lambda n: f"save_gpr(ctx, base, {n})", range(14, 32)),
        ("restgprlr", lambda n: f"rest_gpr(ctx, base, {n})", range(14, 32)),
        ("savefpr", lambda n: f"save_fpr(ctx, base, {n})", range(14, 32)),
        ("restfpr", lambda n: f"rest_fpr(ctx, base, {n})", range(14, 32)),
        ("savevmx", lambda n: f"save_vmx(ctx, base, {n})", list(range(14, 32)) + list(range(64, 128))),
        ("restvmx", lambda n: f"rest_vmx(ctx, base, {n})", list(range(14, 32)) + list(range(64, 128))),
    ]
    for prefix, body, regs in groups:
        for n in regs:
            name = f"__{prefix}_{n}"
            if name not in wanted:
                continue
            lines.append(f'extern "C" void {name}(PPCContext& ctx, uint8_t* base) {{')
            lines.append(f"    {body(n)};")
            lines.append("}")
            lines.append("")
            implemented.add(name)

    OUT.write_text("\n".join(lines), encoding="utf-8")
    remaining = sorted(wanted - implemented)
    print(f"generated {len(implemented)} ABI helpers -> {OUT.relative_to(PROJECT)}")
    if remaining:
        print(f"{len(remaining)} non-ABI symbols remain for runtime_stubs.cpp:")
        print("  " + ", ".join(remaining))
    (PROJECT / "config/runtime_non_abi.json").write_text(json.dumps(remaining, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
